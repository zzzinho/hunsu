export const dictionaries = { en, ko };

export function translator(lang) {
  const dictionary = dictionaries[lang] ?? en;
  const t = (key, params = {}) => (dictionary[key] ?? en[key] ?? key)
    .replace(/\{(\w+)\}/g, (match, name) => params[name] ?? match);
  t.lang = dictionaries[lang] ? lang : 'en';
  return t;
}

const attributes = [
  ['i18n', (element, text) => { element.textContent = text; }],
  ['i18nTitle', (element, text) => { element.title = text; }],
  ['i18nLabel', (element, text) => element.setAttribute('aria-label', text)],
  ['i18nPlaceholder', (element, text) => { element.placeholder = text; }],
];

// data-i18n(글), data-i18n-title, data-i18n-label(aria-label), data-i18n-placeholder 를 고른 언어로 채운다.
export function translatePage(root, t) {
  for (const [name, set] of attributes) {
    const attribute = `data-${name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
    root.querySelectorAll(`[${attribute}]`).forEach((element) => set(element, t(element.dataset[name])));
  }
}

// 서버는 오류를 {"code","message"} 로 알린다. 아는 코드는 고른 언어로 바꾼다.
export function errorMessage(body, t) {
  try {
    const { code, message } = JSON.parse(body);
    const key = `error.${code}`;
    const text = t(key);
    return text === key ? message : text;
  } catch {
    return body;
  }
}
